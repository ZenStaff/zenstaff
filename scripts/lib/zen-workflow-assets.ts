// @effect-diagnostics nodeBuiltinImport:off - Build-time helper for scripts/zen-embed-workflows.ts and its test.
// Zen Staff: collects apps/server/src/zen/workflows/{builtin,packs,registry.json} as text so
// packaged builds can embed them (embeddedAssets.gen.ts). Not used at runtime. ZEN.md, "Office edition".
import * as NodeCrypto from "node:crypto";
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";

/** What gets embedded, relative to the workflows folder. */
export const EMBEDDED_ASSET_ROOTS = ["builtin", "packs", "registry.json"] as const;

/** One stable hash over every path and content, used as the cache folder name. */
export function hashWorkflowAssets(files: Readonly<Record<string, string>>): string {
  const hash = NodeCrypto.createHash("sha256");
  for (const key of Object.keys(files).toSorted()) {
    hash.update(key).update("\0").update(files[key]!).update("\0");
  }
  return hash.digest("hex").slice(0, 16);
}

/** Every file under the embedded roots, keyed by its posix path, sorted. */
export function collectWorkflowAssets(dir: string): Record<string, string> {
  return collectAssetFiles(dir, EMBEDDED_ASSET_ROOTS);
}

/** The toolchain catalog (tools/, connectors.json, advisories.json, npm/, pip/), embedded too. */
export const EMBEDDED_CATALOG_ROOTS = [
  "tools",
  "connectors.json",
  "advisories.json",
  "npm",
  "pip",
] as const;

export function collectCatalogAssets(catalogDir: string): Record<string, string> {
  return collectAssetFiles(catalogDir, EMBEDDED_CATALOG_ROOTS);
}

/** Every file under `roots` (relative to `dir`), keyed by its posix path, sorted. */
export function collectAssetFiles(
  dir: string,
  roots: ReadonlyArray<string>,
): Record<string, string> {
  const files: Record<string, string> = {};
  const walk = (relative: string) => {
    const absolute = NodePath.join(dir, relative);
    const stat = NodeFS.statSync(absolute);
    if (stat.isDirectory()) {
      for (const name of NodeFS.readdirSync(absolute).toSorted()) {
        if (name === ".DS_Store") continue;
        walk(relative === "" ? name : `${relative}/${name}`);
      }
    } else if (stat.isFile()) {
      files[relative] = NodeFS.readFileSync(absolute, "utf8");
    }
  };
  for (const root of roots) walk(root);
  return Object.fromEntries(Object.entries(files).toSorted(([a], [b]) => (a < b ? -1 : 1)));
}

/** The generated module's source text. */
export function renderEmbeddedAssetsModule(files: Readonly<Record<string, string>>): string {
  const lines = [
    "// Generated by scripts/zen-embed-workflows.ts (vp run --filter @t3tools/scripts zen:workflows).",
    "// Do not edit: change builtin/, packs/ or registry.json and run the script again.",
    "// Packaged builds (server bundle, SEA executable, desktop) read workflows from here. ZEN.md.",
    `export const ZEN_WORKFLOW_ASSETS_HASH = ${JSON.stringify(hashWorkflowAssets(files))};`,
    "",
    "export const ZEN_WORKFLOW_ASSETS: Readonly<Record<string, string>> = {",
    ...Object.entries(files).map(
      ([key, value]) => `  ${JSON.stringify(key)}:\n    ${JSON.stringify(value)},`,
    ),
    "};",
    "",
  ];
  return lines.join("\n");
}

/** The generated toolchain catalog module (apps/server/src/zen/toolchains/catalogAssets.gen.ts). */
export function renderEmbeddedCatalogModule(files: Readonly<Record<string, string>>): string {
  const lines = [
    "// Generated by scripts/zen-embed-workflows.ts (vp run --filter @t3tools/scripts zen:workflows).",
    "// Do not edit: change catalog/ and run the script again.",
    "// Packaged builds read the tool catalog and the shipped advisories from here. ZEN.md, Toolchains.",
    `export const ZEN_TOOLCHAIN_CATALOG_HASH = ${JSON.stringify(hashWorkflowAssets(files))};`,
    "",
    "export const ZEN_TOOLCHAIN_CATALOG_ASSETS: Readonly<Record<string, string>> = {",
    ...Object.entries(files).map(
      ([key, value]) => `  ${JSON.stringify(key)}:\n    ${JSON.stringify(value)},`,
    ),
    "};",
    "",
  ];
  return lines.join("\n");
}
