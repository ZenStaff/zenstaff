// Build-time helper for scripts/zen-embed-academy.ts and its test: the built-in Academy lessons
// (apps/server/src/zen/academy/lessons) as text, embedded in packaged builds. ZEN.md, "Academy".
import { collectAssetFiles, hashWorkflowAssets } from "./zen-workflow-assets.ts";

/** What gets embedded, relative to the academy folder. */
export const EMBEDDED_ACADEMY_ROOTS = ["lessons"] as const;

export function collectAcademyAssets(academyDir: string): Record<string, string> {
  return collectAssetFiles(academyDir, EMBEDDED_ACADEMY_ROOTS);
}

/** The generated module's source text. */
export function renderEmbeddedLessonsModule(files: Readonly<Record<string, string>>): string {
  const lines = [
    "// Generated by scripts/zen-embed-academy.ts (vp run --filter @t3tools/scripts zen:academy).",
    "// Do not edit: change lessons/ and run the script again.",
    "// Packaged builds (server bundle, SEA executable, desktop) read the lessons from here. ZEN.md.",
    `export const ZEN_ACADEMY_LESSONS_HASH = ${JSON.stringify(hashWorkflowAssets(files))};`,
    "",
    "export const ZEN_ACADEMY_LESSON_ASSETS: Readonly<Record<string, string>> = {",
    ...Object.entries(files).map(
      ([key, value]) => `  ${JSON.stringify(key)}:\n    ${JSON.stringify(value)},`,
    ),
    "};",
    "",
  ];
  return lines.join("\n");
}

export const hashAcademyAssets = hashWorkflowAssets;
