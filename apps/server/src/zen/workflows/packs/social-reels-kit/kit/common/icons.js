/** Standalone SVG markup for an icon. */
export function iconSvg(name, { size = 24, color = "currentColor", stroke = 2 } = {}) {
  const body = ICONS[name] ?? ICONS["arrow-right"];
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="${color}" stroke-width="${stroke}" stroke-linecap="round" stroke-linejoin="round">${body}</svg>`;
}

/** The icon that fits a contact line: a handle, a website, a phone, an address or opening hours. */
export function contactIcon(line) {
  const text = String(line ?? "").trim();
  if (/^@/.test(text)) return "instagram";
  if (/\S+@\S+\.\S+/.test(text)) return "mail";
  if (/^(\+|0)[\d\s.()-]{6,}$/.test(text)) return "phone";
  if (/^(https?:\/\/)?[\w-]+(\.[\w-]+)+(\/\S*)?$/i.test(text)) return "globe";
  if (/\b\d{1,2}[:.]\d{2}\b|\b\d{1,2}\s*-\s*\d{1,2}\b/.test(text)) return "clock";
  return "map-pin";
}
